# Rules that are allowed to match nothing (text that only appears in some states of the page).
OPTIONAL = {
    'Tap for fees <svg',
    "These are general categories, not an official system. In computer science, the CORE ranking (A*, A, B, C) is a common reference. Always check a conference's publisher and indexing before you submit.",
}


def main():
    s = (ROOT / 'index.html').read_text(encoding='utf-8')
    missed = []
    for rule in R:
        if rule[0] == 're':
            _, pat, repl = rule
            s, n = re.subn(pat, repl, s, flags=re.S)
            key = pat
        else:
            en, zh = rule
            n = s.count(en)
            s = s.replace(en, zh)
            key = en
        # Apostrophe rules come in pairs (' and &#x27;); only one spelling is expected to match.
        if n == 0 and key not in OPTIONAL and not (rule[0] != 're' and _twin_hit(key)):
            missed.append(key)

    out = ROOT / 'zh' / 'index.html'
    out.parent.mkdir(exist_ok=True)
    out.write_text(s, encoding='utf-8', newline='')
    print(f'wrote {out.relative_to(ROOT)}')
    if missed:
        print(f'\nMISSED {len(missed)} rule(s); this text stays in English on the Chinese page:')
        for m in missed:
            print('  -', m[:110])
        return 1
    return 0


_SRC = None


def _twin_hit(m):
    """True when the other apostrophe spelling of this rule did match the English source."""
    global _SRC
    if "'" not in m and '&#x27;' not in m:
        return False
    if _SRC is None:
        _SRC = (ROOT / 'index.html').read_text(encoding='utf-8')
    twin = m.replace('&#x27;', "'") if '&#x27;' in m else m.replace("'", '&#x27;')
    return twin in _SRC


if __name__ == '__main__':
    sys.exit(main())
